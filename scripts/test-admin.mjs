import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chrome',headless:true});
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`${process.env.ADMIN_TEST_URL || 'http://127.0.0.1:8781'}/admin`);
  await page.getByRole('button',{name:'Explore local demo'}).click();
  await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
  assert.equal(await page.getByText('Supabase connected',{exact:true}).count(),0);
  await page.getByRole('button',{name:'Collapse sidebar',exact:true}).click();
  await page.getByRole('button',{name:'Expand sidebar',exact:true}).waitFor();
  await page.getByRole('button',{name:'Expand sidebar',exact:true}).click();
  await page.getByRole('link',{name:'People',exact:true}).click();
  await page.getByRole('link',{name:'Moshe Douglas Teki',exact:true}).click();
  await page.getByLabel('LinkedIn',{exact:true}).fill('https://www.linkedin.com/');
  await page.getByRole('button',{name:'Save draft'}).click();
  await page.getByRole('status').filter({hasText:'Changes saved'}).waitFor();
  await page.getByRole('link',{name:'Overview',exact:true}).click();
  await page.screenshot({path:'/tmp/integral-admin-overview-desktop.png',fullPage:true});
  await page.getByRole('link',{name:'Articles',exact:true}).click();
  await page.getByLabel('Rows per page').selectOption('25');
  await page.getByRole('link',{name:'Create article'}).click();
  await page.getByLabel('Title', {exact:false}).first().fill('Local workflow test');
  assert.equal(await page.getByLabel('URL slug').inputValue(),'local-workflow-test');
  await page.getByLabel('Title', {exact:false}).first().fill('Local workflow test updated');
  assert.equal(await page.getByLabel('URL slug').inputValue(),'local-workflow-test-updated');
  await page.getByLabel('URL slug').fill('local-workflow-test');
  await page.getByLabel('Title', {exact:false}).first().fill('Local workflow test');
  assert.equal(await page.getByLabel('URL slug').inputValue(),'local-workflow-test');
  await page.getByRole('button',{name:'Save draft'}).click();
  await page.getByRole('heading',{name:'Edit article'}).waitFor();
  await page.getByRole('button',{name:'Publish',exact:true}).click();
  assert.match(await page.getByRole('alert').innerText(), /required/);
  await page.getByLabel('Excerpt').fill('Testing publishing and revision history.');
  await page.getByLabel('Category').selectOption('News');
  await page.getByLabel('Author', {exact:false}).fill('Integral Editorial');
  await page.getByRole('textbox',{name:'Article',exact:true}).fill('Verified article content.');
  await page.getByRole('button',{name:'Choose image'}).click();
  await page.getByRole('button',{name:'Business collaboration'}).click();
  await page.getByRole('button',{name:'Publish',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Changes saved'}).waitFor();
  await page.getByRole('button',{name:'Revision history'}).click();
  await page.getByRole('dialog',{name:'Revision history'}).waitFor();
  assert.ok(await page.getByRole('button',{name:'Restore draft'}).count() >= 2);
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/integral-admin-editor-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 1));
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('link',{name:'Training',exact:true}).click();
  await page.getByRole('heading',{name:/Training/}).waitFor();
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('button',{name:'Sign out'}).click();
  await page.getByRole('button',{name:'Explore local demo'}).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: local create/save, publication validation, rich text, media selection, publishing, revision history, mobile navigation, no overflow, logout.');
} finally { await browser.close(); }
